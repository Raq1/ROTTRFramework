"""Writes src/shadow_blend_shaders.inc: the game's sun shadow-mask pixel shaders (embedded in ROTTR.exe) patched to
blend their cascades (patch.py), each with the original's DXBC checksum.
python make_inc.py <ROTTR.exe> <out .inc>"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(__file__))
import dxbc, patch

# the 20 variants (file offsets in the retail ROTTR.exe): 4 x 4-tap, then 4 groups of the gather kernels (3, 9, 14, 21
# gathers), the MSAA depth variants among them
VARIANTS = ['0120D3F8', '0120EE34', '01210878', '012122DC', '01213D58', '01215D38', '0121835C', '0121AFA0', '0121E514',
            '012204FC', '01222B28', '01225774', '01228CF0', '0122ACF8', '0122D344', '0122FFB0', '0123354C', '0123556C',
            '01237BD0', '0123A854']

exe = open(sys.argv[1], 'rb').read()
lines = ['// Generated by tools/shadow_blend/make_inc.py (Framework 0.9.516): the sun\'s shadow-mask pixel shaders of the',
         '// retail ROTTR.exe, patched to blend each shadow cascade into the next over its last %.0f %% (patch.py). Each: the' % (patch.BLEND * 100),
         '// original\'s DXBC checksum (its bytes 4..19), the patched shader, its name, its kernel\'s size and (0.9.570) the',
         '// byte offset of its marker for the probe\'s sun mask (a float, written 0 here: not read; 1: read).', '']
entries = []
for v in VARIANTS:
    off = int(v, 16)
    assert exe[off:off + 4] == b'DXBC', v
    size = struct.unpack_from('<I', exe, off + 24)[0]
    blob = exe[off:off + size]
    patched, info = patch.patch(blob)
    assert dxbc.checksum(patched) == patched[4:20]
    q = bytearray(patched)   # (0.9.570) the sun mask's marker 0 (off) in the shader kept
    q[info['rt']:info['rt'] + 4] = struct.pack('<f', 0.0)
    q[4:20] = dxbc.checksum(bytes(q))
    patched = bytes(q)
    words = struct.unpack('<4I', blob[4:20])
    body = ', '.join('0x%02X' % b for b in patched)
    rows = [body[i:i + 114] for i in range(0, len(body), 114)]
    lines.append('alignas(4) static const unsigned char kShadowBlend_%s[%d] = {' % (v, len(patched)))
    lines.extend('    ' + r.strip() for r in rows)
    lines.append('};')
    entries.append('    {{0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu}, kShadowBlend_%s, sizeof(kShadowBlend_%s), "%s", %d, %d},' %
                   (words + (v, v, v, info['kernel'], info['rt'])))
lines.append('')
lines.append('static const ShadowBlendShader kShadowBlendShaders[] = {')
lines.extend(entries)
lines.append('};')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines) + '\n')
print('written', len(entries), 'shaders')
