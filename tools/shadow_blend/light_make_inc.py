"""Writes src/light_pass_shaders.inc: the game's tiled lighting pixel shaders (embedded in ROTTR.exe) patched by
light_patch.py (softer lamp shadows, contact shadows), each with the original's DXBC checksum and the byte offsets of
the four values the framework writes (contact shadows' strength and length, the lamp taps' inner and centre steps)
before it makes the checksum again.
python light_make_inc.py <ROTTR.exe> <out .inc>"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(__file__))
import dxbc, light_patch

# the 32 TiledLightingPS variants (file offsets in the retail ROTTR.exe): MSAA or not (per pixel / per sample), the
# normals packed or not, the lights' data from t54 or cb12; with 4 comparison taps in all or 6 (two loops of their own)
VARIANTS = ['01473BC8', '01479490', '01480CFC', '01486BE8', '0148EA78', '01494350', '0149BBCC', '014A1AC0', '014A9958',
            '014AF248', '014B6ADC', '014BC9F0', '014C48A8', '014CA1B8', '014D1A6C', '014D7998', '014DF868', '014E5298',
            '014ECC6C', '014F2CC0', '014FACB8', '015006F8', '015080DC', '0150E138', '01516138', '0151BB90', '0152358C',
            '01529608', '01531628', '015370A0', '0153EABC', '01544B50']

exe = open(sys.argv[1], 'rb').read()
lines = ['// Generated by tools/shadow_blend/light_make_inc.py (Framework 0.9.526): the tiled lighting pixel shaders of the',
         '// retail ROTTR.exe, patched (light_patch.py): the spot lights\' shadows over a 4 x 4 grid of comparison taps and',
         '// contact shadows for the sun, point and spot lights. Each: the original\'s DXBC checksum (its bytes 4..19), the',
         '// patched shader, its name (file offset), the byte offsets of its five values (floats): contact strength,',
         '// contact length (cm), the lamp taps\' inner and centre steps (texels), (0.9.537) the debug view (0 / 1),',
         '// (0.9.561) the ray tracing probe\'s lamp shadows (0 / 1: t45 its mask, t46 its lamps).', '']
entries = []
for v in VARIANTS:
    off = int(v, 16)
    assert exe[off:off + 4] == b'DXBC', v
    size = struct.unpack_from('<I', exe, off + 24)[0]
    blob = exe[off:off + size]
    assert dxbc.checksum(blob) == blob[4:20], v
    patched, info = light_patch.patch(blob)
    assert dxbc.checksum(patched) == patched[4:20]
    o = info['offsets']
    words = struct.unpack('<4I', blob[4:20])
    body = ', '.join('0x%02X' % b for b in patched)
    rows = [body[i:i + 114] for i in range(0, len(body), 114)]
    lines.append('alignas(4) static const unsigned char kLightPass_%s[%d] = {' % (v, len(patched)))
    lines.extend('    ' + r.strip() for r in rows)
    lines.append('};')
    entries.append('    {{0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu}, kLightPass_%s, sizeof(kLightPass_%s), "%s", {%d, %d, %d, %d, %d, %d}},' %
                   (words + (v, v, v, o['strength'], o['length'], o['inner'], o['centre'], o['debug'], o['rt'])))
lines.append('')
lines.append('static const LightPassShader kLightPassShaders[] = {')
lines.extend(entries)
lines.append('};')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines) + '\n')
print('written', len(entries), 'shaders')
